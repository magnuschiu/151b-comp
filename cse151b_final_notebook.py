# ===== scoring library (validated offline: 1126/1126 gold round-trip) =====
"""Answer extraction + fallback judging for the CSE 151B math competition.

This module is embedded into the final notebook. It is tested locally by
feeding gold answers back in as predictions (should score ~100%).

Two pieces:
  1. extract_boxed(text)      - brace-aware \boxed{...} extraction (handles \frac{a}{b})
  2. FallbackJudger.judge()   - numeric/symbolic equivalence vs. gold answer list

The competition's judger.py is preferred when available; this is the fallback
so local runs (and crashed-session reruns) can still score.
"""
import re
from fractions import Fraction


# ── 1. boxed extraction ──────────────────────────────────────────────────────

def extract_boxed(text: str) -> str:
    """Return content of the LAST \\boxed{...} in text, brace-aware.

    The starter regex r'\\boxed\\{([^}]+)\\}' truncates nested braces like
    \\boxed{\\frac{5}{8}} -> '\\frac{5'. This walks braces properly.
    """
    if not text:
        return ""
    out = ""
    for m in re.finditer(r"\\boxed\s*\{", text):
        depth = 1
        i = m.end()
        start = i
        while i < len(text) and depth > 0:
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        if depth == 0:
            out = text[start:i - 1].strip()
    return out


def split_top_level_commas(s: str) -> list:
    """Split a multi-part boxed answer '3, 7' on commas not inside (), [], {}."""
    parts, depth, cur = [], 0, []
    for ch in s:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if cur:
        parts.append("".join(cur).strip())
    return [p for p in parts if p]


def extract_mcq_letter(text: str, n_options: int = 26) -> str:
    """Extract an MCQ letter, preferring the boxed answer."""
    boxed = extract_boxed(text)
    if boxed:
        m = re.search(r"[A-Za-z]", boxed)
        if m and len(boxed.strip()) <= 3:
            return m.group(0).upper()
        # boxed contains a full expression; fall through to scan
    matches = re.findall(r"\b([A-Z])\b", text.upper())
    return matches[-1] if matches else ""


# ── 2. fallback judging ──────────────────────────────────────────────────────

_LATEX_REPLACEMENTS = [
    (r"\\left", ""), (r"\\right", ""), (r"\\!", ""), (r"\\,", ""), (r"\\;", ""),
    (r"\\mathrm\{([^}]*)\}", r"\1"), (r"\\text\{([^}]*)\}", r"\1"),
    (r"\\dfrac", r"\\frac"), (r"\\tfrac", r"\\frac"),
    (r"\\cdot", "*"), (r"\\times", "*"), (r"\\div", "/"),
    (r"\\pi", "pi"), (r"\\infty", "oo"),
    (r"\$", ""), (r"\\%", ""), (r"%", ""), (r"\\\$", ""),
    (r"\\ ", " "),
]


def _latex_to_plain(s: str) -> str:
    s = s.strip()
    for pat, rep in _LATEX_REPLACEMENTS:
        s = re.sub(pat, rep, s)
    # \frac{a}{b} -> (a)/(b), applied repeatedly for nesting
    frac = re.compile(r"\\frac\s*\{([^{}]*)\}\s*\{([^{}]*)\}")
    while frac.search(s):
        s = frac.sub(r"((\1)/(\2))", s)
    # \sqrt{a} -> sqrt(a)
    sqrt = re.compile(r"\\sqrt\s*\{([^{}]*)\}")
    while sqrt.search(s):
        s = sqrt.sub(r"sqrt(\1)", s)
    s = s.replace("^", "**").replace("{", "(").replace("}", ")")
    s = s.replace("−", "-")  # unicode minus
    return s.strip()


def _to_number(s: str):
    """Best-effort numeric value of a string, else None."""
    s = s.strip().rstrip(".")
    s = s.replace(",", "")  # 1,000 -> 1000
    try:
        return float(s)
    except ValueError:
        pass
    try:
        return float(Fraction(s))
    except (ValueError, ZeroDivisionError):
        pass
    plain = _latex_to_plain(s)
    try:
        import sympy
        val = sympy.sympify(plain, rational=False)
        if val.is_number:
            return float(val.evalf())
    except Exception:
        pass
    return None


def _norm_str(s: str) -> str:
    s = s.strip().lower()
    s = re.sub(r"\s+", "", s)
    s = s.rstrip(".")
    return s


class FallbackJudger:
    """Numeric/symbolic equivalence judging when the official judger.py is absent.

    Numeric tolerance mirrors the official judger's behavior (verified against
    judger.py): gold is rounded to 6 decimal places and the prediction must match
    it to ~1e-8 relative error. So '143.224229' passes against gold
    '143.224229233795' but '143.224' does not.
    """

    def __init__(self, rel_tol: float = 1.01e-8):
        self.rel_tol = rel_tol

    def parts_equal(self, pred: str, gold: str) -> bool:
        if not pred:
            return False
        # exact normalized string match (covers 'No', '5/8', text answers)
        if _norm_str(pred) == _norm_str(gold):
            return True
        # numeric comparison, mimicking the official judger's gold-rounding rule
        pv, gv = _to_number(pred), _to_number(gold)
        if pv is not None and gv is not None:
            gv6 = round(gv, 6)
            denom = abs(gv6) if gv6 != 0 else 1.0
            if abs(pv - gv6) / denom <= self.rel_tol:
                return True
            # full-precision exact match (official accepts these via string/N() paths)
            return abs(pv - gv) <= 1e-12 * max(1.0, abs(gv))
        # symbolic comparison via sympy
        try:
            import sympy
            pe = sympy.sympify(_latex_to_plain(pred))
            ge = sympy.sympify(_latex_to_plain(gold))
            if sympy.simplify(pe - ge) == 0:
                return True
        except Exception:
            pass
        return False

    def judge(self, pred_text: str, gold) -> bool:
        """pred_text: raw model response. gold: answer list (or single string)."""
        gold_list = gold if isinstance(gold, list) else [gold]
        boxed = extract_boxed(pred_text)
        if not boxed:
            return False
        parts = split_top_level_commas(boxed)
        if len(gold_list) == 1:
            # allow the whole boxed string OR its single part to match
            cands = [boxed] + parts
            return any(self.parts_equal(c, str(gold_list[0])) for c in cands)
        if len(parts) != len(gold_list):
            return False
        return all(self.parts_equal(p, str(g)) for p, g in zip(parts, gold_list))

