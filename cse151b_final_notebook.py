"""## 9. GRPO Fine-Tuning (Runs D and E)

**Free GPU memory first** — the next cell unloads vLLM. On a T4×2 the policy trains on `cuda:1`
while GPU 0 stays clean; on a single GPU the unload below is required.

### What D and E are
Both runs do reinforcement fine-tuning with a binary correctness reward on prompts from the
**80% train split** (`GRPO_TRAIN_SIZE` prompts, stratified). Rollouts use the two-step decoder
with a short reasoning budget; the policy gradient flows through the *sampled reasoning tokens*.

* **Run D (milestone GRPO, improved)** — 1 sample/prompt, fixed-baseline advantage
  `A = r − 0.5` (exactly the estimator we presented), now with checkpointing, correct loss
  masking, gradient clipping, and 2 epochs.
* **Run E (GRPO + LoRA, finished)** — group-relative advantage over `G=4` samples/prompt:
  `A_i = (r_i − mean(r)) / std(r)` (Shao et al., 2024). Groups where every sample gets the same
  reward are skipped (zero advantage).

Both update LoRA adapters (r=16, α=32 on q/v projections, dropout 0.05, lr 2e-5) — full-parameter
RL on a 4B model does not fit in T4 memory, so the runs differ **only in the advantage
estimator and group size**, which is the comparison we care about.

Reward: `1.0` correct · `0.1` well-formed `\boxed{}` but wrong · `0.0` no boxed answer.
The 0.1 format-shaping term keeps the gradient alive early, when correct answers are rare.

Crash-safety: adapter checkpoint + training log every `SAVE_EVERY` steps; rerunning the cell
resumes from the last checkpoint and skips logged steps.
"""

if RUN_D or RUN_E:
    unload_vllm()

    import torch
    from torch.optim import AdamW
    from transformers import AutoModelForCausalLM
    from peft import LoraConfig, get_peft_model, PeftModel

    GRPO_DEVICE = "cuda:1" if torch.cuda.device_count() > 1 else "cuda:0"
    print("GRPO trains on", GRPO_DEVICE)

    def load_policy(resume_dir=None):
        base = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, torch_dtype=torch.float16, device_map=GRPO_DEVICE,
            low_cpu_mem_usage=True, trust_remote_code=True)
        base.config.pad_token_id = TOKENIZER.eos_token_id
        if resume_dir is not None and Path(resume_dir).exists():
            print("Resuming adapter from", resume_dir)
            model = PeftModel.from_pretrained(base, resume_dir, is_trainable=True)
        else:
            lcfg = LoraConfig(r=LORA_R, lora_alpha=LORA_ALPHA,
                              target_modules=["q_proj", "v_proj"],
                              lora_dropout=LORA_DROPOUT, bias="none",
                              task_type="CAUSAL_LM")
            model = get_peft_model(base, lcfg)
        model.enable_input_require_grads()
        model.gradient_checkpointing_enable(
            gradient_checkpointing_kwargs={"use_reentrant": False})
        for p in model.parameters():            # fp32 master copies of LoRA params
            if p.requires_grad:
                p.data = p.data.float()
        model.print_trainable_parameters()
        return model

    def grpo_reward(item, response_text):
        if judge_item(item, response_text):
            return 1.0
        return 0.1 if extract_boxed(response_text) else 0.0

    @torch.no_grad()
    def grpo_rollout(model, item, n_samples):
        '''Sample n responses with the two-step decoder. Returns list of dicts.'''
        # eval() is required: in train mode, gradient checkpointing disables the KV
        # cache and generation becomes quadratically slow.
        model.eval()
        prompt = chat_prompt(item, style="tuned")
        ids = TOKENIZER(prompt, return_tensors="pt",
                        add_special_tokens=False).input_ids.to(GRPO_DEVICE)
        with torch.autocast("cuda", dtype=torch.float16):
            out = model.generate(
                ids, do_sample=True, temperature=GRPO_TEMP, top_p=0.95, top_k=50,
                max_new_tokens=GRPO_STEP1_TOKENS, num_return_sequences=n_samples,
                pad_token_id=TOKENIZER.eos_token_id)
        samples = []
        hint_ids = TOKENIZER(ANSWER_HINT, return_tensors="pt",
                             add_special_tokens=False).input_ids.to(GRPO_DEVICE)
        for k in range(n_samples):
            gen = out[k, ids.shape[1]:]
            gen = gen[gen != TOKENIZER.eos_token_id]      # strip right padding
            text = TOKENIZER.decode(gen, skip_special_tokens=True)
            full_text = text
            if not extract_boxed(text):                   # step 2: inject answer hint
                ctx = torch.cat([ids[0], gen, hint_ids[0]]).unsqueeze(0)
                with torch.autocast("cuda", dtype=torch.float16):
                    ans = model.generate(ctx, do_sample=False, max_new_tokens=24,
                                         pad_token_id=TOKENIZER.eos_token_id)
                ans_text = TOKENIZER.decode(ans[0, ctx.shape[1]:],
                                            skip_special_tokens=True).split("}")[0]
                full_text = text + ANSWER_HINT + ans_text + "}"
            samples.append({"prompt_ids": ids[0], "gen_ids": gen, "text": full_text})
        return samples

    def grpo_update(model, optimizer, scaler, samples, advantages):
        '''One policy-gradient step over a group. Loss masked to sampled reasoning tokens.'''
        optimizer.zero_grad(set_to_none=True)
        n_active, total_loss = 0, 0.0
        for s, adv in zip(samples, advantages):
            if abs(adv) < 1e-8 or s["gen_ids"].numel() == 0:
                continue
            seq = torch.cat([s["prompt_ids"], s["gen_ids"]]).unsqueeze(0)
            p_len = s["prompt_ids"].shape[0]
            with torch.autocast("cuda", dtype=torch.float16):
                logits = model(seq, use_cache=False).logits
            logp = torch.log_softmax(logits[0, :-1].float(), dim=-1)
            tgt = seq[0, 1:]
            tok_logp = logp.gather(1, tgt.unsqueeze(1)).squeeze(1)
            gen_logp = tok_logp[p_len - 1:]               # logprobs of generated tokens
            loss = -(adv * gen_logp.mean()) / len(samples)
            scaler.scale(loss).backward()
            total_loss += float(loss.detach())
            n_active += 1
        if n_active == 0:
            return None
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(
            [p for p in model.parameters() if p.requires_grad], 1.0)
        scaler.step(optimizer)
        scaler.update()
        return total_loss

    def train_grpo(run_name, *, mode, group_size, epochs, train_pool):
        '''mode='fixed' (Run D, A = r - 0.5) or 'group' (Run E, group-relative).'''
        ckpt_dir = OUTPUT_DIR / f"{run_name}_adapter"
        log_path = OUTPUT_DIR / f"{run_name}_train_log.jsonl"
        prompts = stratified_take(train_pool, GRPO_TRAIN_SIZE, SEED + 7)
        schedule = []
        for ep in range(epochs):
            order = list(prompts)
            random.Random(SEED + ep).shuffle(order)
            schedule += order
        done_steps = sum(1 for _ in open(log_path, encoding="utf-8")) if log_path.exists() else 0
        print(f"[{run_name}] {len(schedule)} total steps, resuming at step {done_steps}")
        model = load_policy(resume_dir=ckpt_dir if done_steps > 0 else None)
        model.train()
        optimizer = AdamW([p for p in model.parameters() if p.requires_grad], lr=GRPO_LR)
        scaler = torch.amp.GradScaler("cuda")
        recent_rewards = []
        t0 = time.time()
        for step, item in enumerate(schedule):
            if step < done_steps:
                continue
            samples = grpo_rollout(model, item, group_size)
            rewards = [grpo_reward(item, s["text"]) for s in samples]
            if mode == "fixed":
                advantages = [r - GRPO_BASELINE for r in rewards]
            else:
                mu = sum(rewards) / len(rewards)
                sd = (sum((r - mu) ** 2 for r in rewards) / len(rewards)) ** 0.5
                advantages = [0.0] * len(rewards) if sd < 1e-6 else \
                             [(r - mu) / (sd + 1e-4) for r in rewards]
            model.train()
            loss = grpo_update(model, optimizer, scaler, samples, advantages)
            recent_rewards += rewards
            with open(log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps({"step": step, "id": item["id"], "rewards": rewards,
                                    "loss": loss,
                                    "gen_tokens": [int(s["gen_ids"].shape[0]) for s in samples]
                                    }) + "\n")
            if (step + 1) % SAVE_EVERY == 0 or step == len(schedule) - 1:
                model.save_pretrained(ckpt_dir)
                window = recent_rewards[-SAVE_EVERY * group_size:]
                print(f"[{run_name}] step {step+1}/{len(schedule)} | "
                      f"mean reward (last {len(window)}) {sum(window)/max(len(window),1):.3f} | "
                      f"{(time.time()-t0)/60:.1f} min | checkpoint saved")
        model.save_pretrained(ckpt_dir)
        print(f"[{run_name}] training complete -> {ckpt_dir}")
        del model, optimizer
        gc.collect()
        torch.cuda.empty_cache()
        return ckpt_dir

