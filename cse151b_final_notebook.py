def stratified_split(items, test_frac, seed):
    rng = random.Random(seed)
    mcq  = [d for d in items if d.get("options")]
    free = [d for d in items if not d.get("options")]
    train, test = [], []
    for group in (mcq, free):
        idx = list(range(len(group)))
        rng.shuffle(idx)
        n_test = round(len(group) * test_frac)
        test  += [group[i] for i in idx[:n_test]]
        train += [group[i] for i in idx[n_test:]]
    train.sort(key=lambda d: d["id"]); test.sort(key=lambda d: d["id"])
    return train, test

def stratified_take(items, n, seed):
    rng = random.Random(seed)
    mcq  = [d for d in items if d.get("options")]
    free = [d for d in items if not d.get("options")]
    n = min(n, len(items))
    n_mcq = min(len(mcq), round(n * len(mcq) / len(items)))
    take = rng.sample(mcq, n_mcq) + rng.sample(free, n - n_mcq)
    take.sort(key=lambda d: d["id"])
    return take

