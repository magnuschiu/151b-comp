from transformers import StoppingCriteria, StoppingCriteriaList

class BoxedStoppingCriteria(StoppingCriteria):
    def __init__(self, tokenizer):
        self.tokenizer = tokenizer
        # Tokenize the start of \boxed{
        self.boxed_start = tokenizer.encode("\\boxed{", add_special_tokens=False)
        self.boxed_start_len = len(self.boxed_start)

    def __call__(self, input_ids, scores, **kwargs):
        # Check if the last tokens match the start of \boxed{
        if input_ids.shape[1] >= self.boxed_start_len:
            last_tokens = input_ids[0, -self.boxed_start_len:].tolist()
            if last_tokens == self.boxed_start:
                return True
        return False

