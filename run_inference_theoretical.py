def extract_boxed_answer(response: str) -> str:
    """Extract the content inside \boxed{}."""
    import re
    match = re.search(r'\\boxed\{([^}]+)\}', response)
    return match.group(1).strip() if match else ""

def majority_vote(responses: list[str]) -> str:
    """Return the most common boxed answer from multiple responses."""
    from collections import Counter
    answers = [extract_boxed_answer(r) for r in responses if extract_boxed_answer(r)]
    if not answers:
        return responses[0] if responses else ""
    return Counter(answers).most_common(1)[0][0]

